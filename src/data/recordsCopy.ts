export function recordsError(lang: "en" | "fr", code: string | undefined) {
  const copy = recordsCopy[lang];
  if (code === "forbidden") return copy.forbidden;
  if (code === "guardian_required") return copy.guardian;
  if (code === "email_in_use") return copy.emailUsed;
  if (code === "card_not_accepted") return copy.card;
  if (code === "unconfigured" || code === "database_down") return copy.unconfigured;
  return copy.invalid;
}
